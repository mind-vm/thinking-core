// jsReserved are names that cannot head a `declare function` or be
// called bare. The generated module only uses them as property names,
// where they would work, but the model reads the declaration as plain
// TypeScript and a function called `delete` there does not parse.
var jsReserved = map[string]bool{
	"break": true, "case": true, "catch": true, "class": true, "const": true, "continue": true,
	"debugger": true, "default": true, "delete": true, "do": true, "else": true, "enum": true,
	"export": true, "extends": true, "false": true, "finally": true, "for": true, "function": true,
	"if": true, "import": true, "in": true, "instanceof": true, "new": true, "null": true,
	"return": true, "super": true, "switch": true, "this": true, "throw": true, "true": true,
	"try": true, "typeof": true, "var": true, "void": true, "while": true, "with": true, "yield": true,
	"let": true, "static": true, "await": true, "async": true,
}

var tsIdentRe = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

// mcpFuncName turns an MCP tool name ("get_file-contents", "SearchRepos")
// into a camelCase JS identifier ("getFileContents", "searchRepos").
// Word boundaries are any non-alphanumeric run; humps already inside a
// word are kept, so a server that already camelCases is left alone.
func mcpFuncName(name string) string {
	fields := strings.FieldsFunc(name, func(r rune) bool {
		return !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9')
	})
	var b strings.Builder
	for i, f := range fields {
		if i == 0 {
			b.WriteString(strings.ToLower(f[:1]))
		} else {
			b.WriteString(strings.ToUpper(f[:1]))
		}
		b.WriteString(f[1:])
	}
	out := b.String()
	if out == "" {
		return "_"
	}
	if out[0] >= '0' && out[0] <= '9' {
		out = "_" + out
	}
	if jsReserved[out] {
		out += "Tool"
	}
	return out
}

// renderMCPModuleJS is the require()-able module: a thin wrapper per tool
// that calls the Go bridge and turns its {ok, v} into a return or a
// throw. Names go through %q, which is valid JS for the ASCII-and-escape
// strings MCP tool names are.
func renderMCPModuleJS(bridge string, tools []mcpTool) string {
	var b strings.Builder
	b.WriteString("// Generated by ext.MCPPack — do not edit by hand.\n")
	b.WriteString("function _unwrap(r) { if (!r.ok) { throw new Error(r.v); } return r.v; }\n")
	for _, t := range tools {
		fmt.Fprintf(&b, "exports[%q] = function(args) { return _unwrap(%s(%q, args)); };\n", t.fn, bridge, t.Name)
	}
	return b.String()
}

// renderMCPModule renders every tool as a TypeScript declaration inside
// an ambient module, which says what require() returns as well as what
// each function takes.
func renderMCPModule(module string, tools []mcpTool) string {
	var b strings.Builder
	fmt.Fprintf(&b, "declare module %q {\n", module)
	for _, t := range tools {
		b.WriteString(renderMCPDecl(t))
	}
	b.WriteString("}")
	return b.String()
}

func renderMCPDecl(t mcpTool) string {
	var b strings.Builder
	desc := firstLine(t.Description)
	if desc == "" {
		desc = t.Name
	}
	if !t.ReadOnly {
		desc += " (changes something; may ask the user)"
	}
	fmt.Fprintf(&b, "  /** %s */\n", strings.ReplaceAll(desc, "*/", "* /"))

	typ := "{}"
	optional := "?"
	if props, _ := t.InputSchema["properties"].(map[string]any); len(props) > 0 {
		typ = tsObject(t.InputSchema, 0)
		if len(requiredSet(t.InputSchema)) > 0 {
			optional = ""
		}
	}
	fmt.Fprintf(&b, "  function %s(args%s: %s): any;\n", t.fn, optional, typ)
	return b.String()
}

func requiredSet(schema map[string]any) map[string]bool {
	out := map[string]bool{}
	if req, ok := schema["required"].([]any); ok {
		for _, r := range req {
			if s, ok := r.(string); ok {
				out[s] = true
			}
		}
	}
	return out
}

// maxTSDepth bounds how far nested schemas are spelled out. Beyond it a
// value is `any`: a deeply nested input schema is the one thing that can
// make one declaration larger than the rest of the prompt combined.
const maxTSDepth = 3

// tsObject renders an object schema as an inline TypeScript type, with
// each top-level property's description as a leading doc comment.
func tsObject(schema map[string]any, depth int) string {
	props, _ := schema["properties"].(map[string]any)
	if len(props) == 0 {
		if depth > 0 {
			return "Record<string, any>"
		}
		return "{}"
	}
	req := requiredSet(schema)
	names := make([]string, 0, len(props))
	for n := range props {
		names = append(names, n)
	}
	sort.Strings(names)

	var parts []string
	for _, n := range names {
		ps, _ := props[n].(map[string]any)
		opt := "?"
		if req[n] {
			opt = ""
		}
		key := n
		if !tsIdentRe.MatchString(n) {
			key = strconv.Quote(n)
		}
		field := fmt.Sprintf("%s%s: %s;", key, opt, tsFromSchema(ps, depth+1))
		if d, _ := ps["description"].(string); depth == 0 && firstLine(d) != "" {
			field = fmt.Sprintf("/** %s */ %s", strings.ReplaceAll(firstLine(d), "*/", "* /"), field)
		}
		parts = append(parts, field)
	}
	return "{ " + strings.Join(parts, " ") + " }"
}

// tsFromSchema renders one JSON Schema fragment as a TypeScript type. It
// covers what tool schemas use in practice — primitives, enum/const,
// arrays, nested objects, type unions, anyOf/oneOf — and falls back to
// `any` for the rest ($ref, allOf, ...), because a wrong precise type
// misleads the model more than an honest `any` does.
func tsFromSchema(s map[string]any, depth int) string {
	if s == nil || depth > maxTSDepth {
		return "any"
	}
	if vals, ok := s["enum"].([]any); ok && len(vals) > 0 {
		lits := make([]string, 0, len(vals))
		for _, v := range vals {
			switch x := v.(type) {
			case string:
				lits = append(lits, strconv.Quote(x))
			case float64, bool:
				lits = append(lits, fmt.Sprint(x))
			case nil:
				lits = append(lits, "null")
			default:
				return "any"
			}
		}
		return strings.Join(lits, " | ")
	}
	if c, ok := s["const"].(string); ok {
		return strconv.Quote(c)
	}
	for _, key := range []string{"anyOf", "oneOf"} {
		if alts, ok := s[key].([]any); ok && len(alts) > 0 {
			var out []string
			for _, a := range alts {
				am, _ := a.(map[string]any)
				out = append(out, tsFromSchema(am, depth+1))
			}
			return strings.Join(dedupeStrings(out), " | ")
		}
	}
	switch t := s["type"].(type) {
	case string:
		return tsFromType(t, s, depth)
	case []any:
		var out []string
		for _, e := range t {
			if es, ok := e.(string); ok {
				out = append(out, tsFromType(es, s, depth))
			}
		}
		if len(out) > 0 {
			return strings.Join(dedupeStrings(out), " | ")
		}
	}
	if _, ok := s["properties"]; ok {
		return tsObject(s, depth)
	}
	return "any"
}

func tsFromType(t string, s map[string]any, depth int) string {
	switch t {
	case "string":
		return "string"
	case "integer", "number":
		return "number"
	case "boolean":
		return "boolean"
	case "null":
		return "null"
	case "array":
		items, _ := s["items"].(map[string]any)
		inner := tsFromSchema(items, depth+1)
		if strings.ContainsAny(inner, " |") {
			inner = "(" + inner + ")"
		}
		return inner + "[]"
	case "object":
		return tsObject(s, depth)
	}
	return "any"
}

func dedupeStrings(in []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, s := range in {
		if !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	return out
}

// mcpPrompt is the pack's entire interface to the model. Few tools get
// their declarations inline; many get a catalog and a pointer to
// skillGet, the way OpenAPIPack keeps a large API out of every turn.
func mcpPrompt(module, description string, tools []mcpTool, decls string, inline int) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// --- MCP server: %s ---\n", strings.TrimPrefix(module, "mcp/"))
	fmt.Fprintf(&b, "/** %s. const srv = require(%q) gives one synchronous function per tool, each taking one args object. ", strings.ReplaceAll(strings.TrimRight(description, ". "), "*/", "* /"), module)
	b.WriteString("It returns the tool's structured result, else its text (a JSON object or array is parsed). A failed tool throws an Error with the server's message. Tools marked as changing something may ask the user first. */\n")
	if len(tools) <= inline {
		b.WriteString(decls)
		return b.String()
	}
	fmt.Fprintf(&b, "// %d tools; skillGet(%q) returns the full TypeScript declarations. Tools:\n", len(tools), module)
	for i, t := range tools {
		if i == maxCatalogLines {
			fmt.Fprintf(&b, "//   … and %d more\n", len(tools)-maxCatalogLines)
			break
		}
		line := firstLine(t.Description)
		if len(line) > 100 {
			line = line[:100] + "…"
		}
		fmt.Fprintf(&b, "//   %s — %s\n", t.fn, line)
	}
	return strings.TrimRight(b.String(), "\n")
}
